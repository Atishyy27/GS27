"""gen_pyq_seed.py: writes apps/web/supabase/migrations/0013_seed_me46018.sql.

Usage: python gen_pyq_seed.py --pack <folder with pyq-source.json and units/uN/pyq-solutions.json> [--out <file>]
Source: the ME46018 course pack (pyq-source.json = 83 questions; units/uN/pyq-solutions.json = solutions).
Seeds one subject (Automobile Engineering, Mech sem 7, SGSITS), its papers, questions, repeat links and
version-1 solutions. Foreign keys are subselects on names and ext_ids, so the seed carries no hard-coded ids.
"""
import argparse, glob, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ap = argparse.ArgumentParser()
ap.add_argument("--pack", required=True)
ap.add_argument("--out", default=os.path.normpath(os.path.join(HERE, "..", "migrations", "0013_seed_me46018.sql")))
ARGS = ap.parse_args()
PACK = ARGS.pack
OUT = ARGS.out
SUBJECT = "Automobile Engineering"
CODE = "ME46018"
BRANCH = "Mech"  # same branch code as 0010_seed_sgsits.sql and colleges.branches
SEM = 7
LABEL = re.compile(r"^Q([1-5])(?:\(([a-e])\))?( OR)?$")


def q(s):
    return "null" if s is None else "'" + str(s).replace("'", "''") + "'"


def body_of(s):
    out = ["**What it asks:** " + s["asks"]]
    if s.get("given"):
        out.append("**Given:**\n" + "\n".join("- " + str(g) for g in s["given"]))
    if s.get("find"):
        out.append("**To find:**\n" + "\n".join("- " + str(f) for f in s["find"]))
    steps = []
    for i, st in enumerate(s["steps"], 1):
        head = f"{i}. " + (st["part"] + " " if st.get("part") else "") + st["say"]
        steps.append(head + ("\n" + st["latex"] if st.get("latex") else ""))
    out.append("\n".join(steps))
    out.append("**Answer:** " + s["answer"])
    out.append("**Exam tip:** " + s["examTip"])
    return "\n\n".join(out)


src = json.load(open(os.path.join(PACK, "pyq-source.json"), encoding="utf-8"))
sol = {}
for p in sorted(glob.glob(os.path.join(PACK, "units", "u*", "pyq-solutions.json"))):
    sol.update(json.load(open(p, encoding="utf-8")))

ids = [x["id"] for x in src]
assert len(src) == 83 and len(set(ids)) == 83, "expected 83 unique questions"
assert set(sol) == set(ids), "solutions and questions must cover the same ids"

exams = []
for x in src:
    if x["exam"] not in exams:
        exams.append(x["exam"])
papers = []
for e in exams:
    items = [x for x in src if x["exam"] == e]
    code = next((x["code"] for x in items if x.get("code")), None)
    year = int(re.search(r"(20\d\d)", e).group(1))
    papers.append((e, year, code))

L = ["-- GENERATED by apps/web/supabase/gen/gen_pyq_seed.py. Edit the generator, not this file.",
     "-- Seeds past questions for ME46018 Automobile Engineering (SGSITS, Mech sem 7) from the ME46018 pack.",
     "",
     "do $seed$",
     "declare c bigint := (select id from public.colleges where slug = 'sgsits'); s bigint;",
     "begin",
     f"  insert into public.subjects (branch, semester, name, code) values ('{BRANCH}', {SEM}, {q(SUBJECT)}, {q(CODE)}) on conflict do nothing;",
     f"  select id into s from public.subjects where lower(name) = lower({q(SUBJECT)});",
     f"  insert into public.subject_offerings (college_id, subject_id, branch, semester, code) "
     f"values (c, s, '{BRANCH}', {SEM}, {q(CODE)}) on conflict do nothing;",
     ]

for e, year, code in papers:
    L.append(f"  insert into public.papers (subject_id, college_id, exam, year, paper_code) "
             f"values (s, c, {q(e)}, {year}, {q(code)}) on conflict (subject_id, exam) do nothing;")

for x in src:
    m = LABEL.match(x["label"].strip())
    assert m, f"unparsed label {x['label']!r} on {x['id']}"
    q_no = int(m.group(1))
    part = m.group(2) or "a"  # mid-sem labels like 'Q1' carry no part letter
    is_or = bool(m.group(3)) or bool(x.get("or"))
    unit = int(x["slotUnit"][1:])
    paper = f"(select p.id from public.papers p where p.subject_id = s and p.exam = {q(x['exam'])})"
    L.append(f"  insert into public.questions (paper_id, ext_id, q_no, part, is_or, marks, unit, text) values "
             f"({paper}, {q(x['id'])}, {q_no}, {q(part)}, {'true' if is_or else 'false'}, "
             f"{x['marks'] if x.get('marks') is not None else 'null'}, {unit}, {q(x['text'])}) on conflict (ext_id) do nothing;")

links = []
seen = set()
for x in src:
    rep = sol[x["id"]].get("repeat") or {}
    of = rep.get("of")
    if not of:
        continue
    assert of in ids and of != x["id"], f"bad repeat target {of} on {x['id']}"
    kind = rep["type"] if rep.get("type") in ("exact", "concept") else "related"
    if (x["id"], of) in seen:
        continue
    seen.add((x["id"], of))
    links.append((x["id"], of, kind))
    L.append(f"  insert into public.question_links (from_id, to_id, kind) values "
             f"((select id from public.questions where ext_id = {q(x['id'])}), "
             f"(select id from public.questions where ext_id = {q(of)}), {q(kind)}) on conflict (from_id, to_id) do nothing;")

for x in src:
    L.append(f"  insert into public.solutions (question_id, version, body_md) values "
             f"((select id from public.questions where ext_id = {q(x['id'])}), 1, {q(body_of(sol[x['id']]['solution']))}) "
             f"on conflict (question_id, version) do nothing;")

L += ["end $seed$;", ""]
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(L))

by_kind = {k: sum(1 for _, _, kk in links if kk == k) for k in ("exact", "concept", "related")}
print("wrote", OUT)
print("questions", len(src))
print("papers", len(papers), [p[0] for p in papers])
print("links", len(links), by_kind)
print("solutions", len(src))
