"""gen_syllabus_seed.py: writes apps/web/supabase/migrations/0016_seed_syllabus_mech_pilot.sql from a syllabus JSON.

Usage: python gen_syllabus_seed.py [--in <json>] [--out <sql>]
The JSON holds the extracted structure only (codes, names, credits, units). It is copied by hand from the official PDF,
which is not stored in this repository. The seed is a migration file: it is never applied by this project's tooling.
"""
import argparse, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
ap = argparse.ArgumentParser()
ap.add_argument("--in", dest="inp", default=os.path.join(HERE, "..", "seed-data", "syllabus-mech-2023-24-pilot.json"))
ap.add_argument("--out", default=os.path.join(HERE, "..", "migrations", "0016_seed_syllabus_mech_pilot.sql"))
ARGS = ap.parse_args()


def q(s):
    return "null" if s is None else "'" + str(s).replace("'", "''") + "'"


data = json.load(open(ARGS.inp, encoding="utf-8"))
meta = data["meta"]
rows = data["subjects"]
codes = [r["code"] for r in rows]
assert len(set(codes)) == len(codes), "duplicate subject code"
for r in rows:
    assert [u["no"] for u in r["units"]] == list(range(1, len(r["units"]) + 1)), r["code"]
    assert all(u["text"].strip() for u in r["units"]), r["code"]

L = [
    "-- GENERATED by apps/web/supabase/gen/gen_syllabus_seed.py from seed-data/syllabus-mech-2023-24-pilot.json. Edit those, not this file.",
    f"-- Pilot: {len(rows)} Mechanical subjects, scheme {meta['scheme_year']}. Subjects and semesters are not created here: the PDF has no",
    "-- semester table, so a subject page shows its syllabus once an offering with the same code exists.",
    "",
    "insert into public.subject_syllabus (college_id, branch, code, name, scheme_year, ltp, credits_total, prerequisites, units, source_url, source_page, source_note)",
    "select (select id from public.colleges where slug = " + q(meta["college_slug"]) + "), v.* from (values",
]
vals = []
for r in rows:
    units = json.dumps(r["units"], ensure_ascii=False, separators=(",", ":"))
    assert "$u$" not in units
    note = meta["source_note"] + (" " + r["unit_note"] if r.get("unit_note") else "")
    vals.append(
        f"  ({q(meta['branch'])}, {q(r['code'])}, {q(r['name'])}, {q(meta['scheme_year'])}, {q(r['ltp'])}, "
        f"{r['credits_total'] if r.get('credits_total') is not None else 'null'}, {q(r['prerequisites'])}, "
        f"$u${units}$u$::jsonb, {q(meta['source_url'])}, {q(r['page'])}, {q(note)})"
    )
L.append(",\n".join(vals))
L.append(") as v(branch, code, name, scheme_year, ltp, credits_total, prerequisites, units, source_url, source_page, source_note)")
L.append("on conflict (college_id, branch, code, scheme_year) do nothing;")
L.append("")
with open(ARGS.out, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(L))

print("wrote", ARGS.out)
print("subjects", len(rows), codes)
print("units", sum(len(r["units"]) for r in rows))
